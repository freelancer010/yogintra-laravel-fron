2. General Refund Conditions
Refund requests are reviewed according to the nature of the service purchased and the applicable cancellation terms communicated at the time of booking.
A payment does not automatically become refundable simply because a user is unable to attend a scheduled session.
Where a refund is available, the eligible refund amount may depend on:
The time of cancellation.
Whether the service has already started.
Whether a session has already been completed.
The type of service or program purchased.
Any applicable cancellation charges.
Administrative or payment-processing costs, where applicable.
Special terms communicated for a particular program, event, retreat, or package.
3. Cancellation by the Customer
If you need to cancel a booking, please contact YogIntra as soon as possible using the official contact details provided on our website.
For services that permit cancellation, refunds may be provided according to the cancellation terms applicable to that service.
Cancellations made sufficiently in advance may qualify for a refund or rescheduling, subject to the specific service policy.
Late cancellations, missed sessions, or cancellations made after the applicable cancellation period may not qualify for a refund.
4. Rescheduling
Where permitted, customers may request to reschedule a yoga session instead of requesting a refund.
Rescheduling is subject to instructor availability, service availability, location, program schedule, and applicable booking conditions.
YogIntra may limit the number of times a booking can be rescheduled.
A rescheduled session may be subject to the same terms and conditions as the original booking.
5. Missed Sessions and No-Shows
If a customer fails to attend or participate in a confirmed session without providing sufficient advance notice, the session may be treated as a no-show.
Completed or missed sessions may not be eligible for a refund.
For online sessions, technical problems on the customer's side, including internet connectivity, device issues, electricity interruptions, or incompatible software, generally do not automatically qualify for a refund.
Where appropriate, YogIntra may consider exceptional circumstances at its discretion.
6. Refunds for Online Yoga Sessions
For private or group online yoga sessions, refunds depend on the applicable booking and cancellation conditions.
If a session cannot be conducted because of a technical issue attributable to YogIntra, YogIntra may offer a replacement session, rescheduling, or refund as appropriate.
If the interruption is caused by the customer's internet connection, device, electricity supply, or other circumstances outside YogIntra's reasonable control, a refund may not be available.
7. Home Visit Yoga Refunds
For home-visit yoga sessions, customers should provide adequate notice when requesting cancellation or rescheduling.
Where an instructor has already been scheduled or has travelled to the agreed location, cancellation or no-show charges may apply.
If a home-visit session cannot be conducted because of circumstances attributable to YogIntra, an alternative session, rescheduling, or eligible refund may be offered.
8. Workshops, Retreats and Special Programs
Workshops, retreats, teacher training courses, and other special programs may have separate cancellation and refund conditions.
Because these programs may involve advance arrangements, instructor commitments, venue bookings, travel arrangements, equipment, and other operational costs, cancellation terms may be stricter than those applicable to individual yoga sessions.
The applicable refund terms should be reviewed before purchasing or registering for such programs.
9. Yoga Teacher Training Courses
Payments made toward a Yoga Teacher Training Course (TTC) may be subject to program-specific cancellation and refund conditions.
Once course materials, training sessions, accommodation, venue arrangements, or other program resources have been provided or committed, the refundable amount may be reduced or become non-refundable.
Any special TTC refund conditions communicated during registration will apply to that particular course.
10. Corporate Yoga Services
Corporate yoga programs may involve customized schedules, instructor allocation, advance planning, and organizational commitments.
Cancellation or refund requests for corporate programs will be evaluated according to the agreement or commercial terms applicable to the organization.
Where a corporate contract contains separate payment, cancellation, or refund provisions, those provisions will take precedence for the applicable service.
11. Refunds for YogIntra-Cancelled Services
If YogIntra cancels a service or program and cannot provide a suitable replacement or rescheduled session, customers may be eligible for a refund of the applicable amount paid.
The available remedy may include:
Full or partial refund.
Rescheduling.
Replacement session.
Credit toward another eligible YogIntra service.
The appropriate option may depend on the circumstances and nature of the service.
