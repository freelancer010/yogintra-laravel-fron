YogIntra understands that unexpected circumstances may occasionally prevent customers from attending a scheduled service.
Refund or rescheduling requests involving exceptional circumstances may be reviewed individually.
Customers may be asked to provide reasonable information or supporting documentation where appropriate.
Approval of an exception is at YogIntra's discretion and does not establish an automatic entitlement to a refund in future circumstances.
